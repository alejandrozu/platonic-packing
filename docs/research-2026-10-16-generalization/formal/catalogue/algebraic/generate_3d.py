"""Emit kernel-checkable actual algebraic packing instances and source registry.

Generation is not verification. Receipts must hash every transitive local Lean
dependency, the exact native witness, derived proposal and generated source.
"""
from fractions import Fraction as Q
from pathlib import Path
import argparse
import hashlib
import json

HERE=Path(__file__).resolve().parent
FORMAL=HERE.parents[1]
from geometry_intervals import rat,interval,vector

def nested(xs,depth,render):
    return render(xs)if depth==0 else vector(xs,lambda x:nested(x,depth-1,render))
def filehash(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def generate(path,write=True):
    path=Path(path).resolve()
    c=json.loads(path.read_text());t=json.loads((HERE/'geometry-intervals.json').read_text())['templates']
    ident=c['record_id'];p=c['piece'];v=c['container'];pt=t[p];vt=t[v]
    n=c['n'];k=pt['vertex_count'];l=vt['vertex_count'];bases=c['container_bases'];b=len(bases)
    remap={z['id']:i for i,z in enumerate(bases)}
    output=FORMAL/'PackingCertificates/Algebraic/Generated/Records'/f'{ident}.lean';output.parent.mkdir(exist_ok=True)
    mods=list(dict.fromkeys(['PackingCertificates.Algebraic.Packing',f'PackingCertificates.Algebraic.Generated.{p}',f'PackingCertificates.Algebraic.Generated.{v}']))
    rows=['import '+m for m in mods]+['','set_option maxRecDepth 0','set_option maxHeartbeats 0','',
        f'namespace PackingCertificates.Algebraic.Generated.Records.{ident}','',
        'open PackingCertificates.Algebraic.Packing','',
        f'def certificate : Certificate {n} {k} {l} {b} where',
        f'  piece := {p}',f'  container := {v}',f'  pieceRoot := {pt["root_id"]}_checked',f'  containerRoot := {vt["root_id"]}_checked',
        f'  containerDegree := {len(vt["coefficients"][0][0])}',
        '  scale := '+rat(c['scale']),'  containerCenter := '+nested(c['container_center'],1,rat),
        '  quaternion := '+nested(c['quaternions'],2,rat),'  rotation := '+nested(c['rotations'],3,rat),'  center := '+nested(c['centres'],2,rat),
        '  placedIntervals := '+nested(c['placed_vertex_intervals'],3,interval),
        '  normalizedIntervals := '+nested(c['normalized_vertex_intervals'],3,interval),
        '  basisIndices := '+nested([z['indices']for z in bases],2,str),
        '  basisDeterminants := '+nested([z['determinant_interval']for z in bases],1,interval),
        '  basisAdjugates := '+nested([z['cofactor_columns']for z in bases],3,interval),
        '  vertexBasis := '+nested([[remap[z['basis']]for z in rr]for rr in c['containment']],2,str),
        '  epsilon := '+nested([[z['epsilon']for z in rr]for rr in c['containment']],2,rat)]
    planegrid=[[dict(normal=['0','0','0'],lower='0',upper='1')for _ in range(n)]for _ in range(n)]
    for z in c['planes']:planegrid[z['i']][z['j']]=z
    def renderplane(z):return '⟨'+nested(z['normal'],1,rat)+', '+rat(z['lower'])+', '+rat(z['upper'])+'⟩'
    rows+=['  separation := '+nested(planegrid,2,renderplane),'',
        'theorem source_checked : certificate.sourceCheck = true := by decide +kernel',
        'theorem templates_checked : certificate.templateCheck = true := by',
        f'  change ({p}.normalizationCheck && ({p}.verticesCheck && ({v}.normalizationCheck && ({v}.verticesCheck && {v}.centroidCheck {len(vt["coefficients"][0][0])})))) = true',
        '  simp only ['+', '.join(dict.fromkeys([p+'_normalization_checked',p+'_vertices_checked',v+'_normalization_checked',v+'_vertices_checked',v+'_centroid_checked']))+'] <;> rfl',
        'theorem placements_checked : certificate.placementCheck = true := by decide +kernel',
        'theorem bases_checked : certificate.basisCheck = true := by decide +kernel',
        'theorem containment_checked : certificate.containmentCheck = true := by decide +kernel',
        'theorem pairs_checked : certificate.pairsCheck = true := by decide +kernel','',
        'theorem checked : certificate.check = true := by',
        '  simp only [Certificate.check,source_checked,templates_checked,placements_checked,bases_checked,containment_checked,pairs_checked] <;> rfl','',
        'theorem valid : certificate.Valid := certificate.check_sound checked','',
        '#print axioms valid',f'end PackingCertificates.Algebraic.Generated.Records.{ident}','']
    # Preserve the already published/hashed Windows-generated byte convention
    # explicitly on every platform; Git attributes mark these assets -text.
    rendered='\n'.join(rows).replace('\n','\r\n').encode('utf8')
    if write:output.write_bytes(rendered)
    elif not output.is_file()or output.read_bytes()!=rendered:
        raise ValueError('Generated Lean source differs from exact deterministic proposal transcription: '+ident)
    return dict(record_id=ident,dimension=3,piece=p,container=v,n=n,
        source_path=c['source_path'],source_sha256=c['source_sha256'],source_freeze=c['source_freeze'],
        proposal_path=path.relative_to(FORMAL).as_posix(),proposal_sha256=filehash(path),
        generated_module=output.relative_to(FORMAL).as_posix(),generated_source_sha256=filehash(output),
        expected_declaration=f'PackingCertificates.Algebraic.Generated.Records.{ident}.valid',
        canonical_template_modules=list(dict.fromkeys([f'PackingCertificates/Algebraic/Generated/{p}.lean',f'PackingCertificates/Algebraic/Generated/{v}.lean'])),
        geometry_source_path='catalogue/algebraic/inputs/src/solids_exact.json',geometry_source_sha256=c['geometry_sha256'],
        geometry_intervals_path='catalogue/algebraic/geometry-intervals.json',geometry_intervals_sha256=filehash(HERE/'geometry-intervals.json'),
        status='GENERATED_NOT_LEAN_VERIFIED')

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--only',nargs='*');ap.add_argument('--all',action='store_true');a=ap.parse_args()
    registry=[]
    pilot_ids={r['record_id']for r in json.loads((HERE/'export3d-report.json').read_text())['exported']}
    for path in sorted((HERE/'witnesses3d').glob('*.json')):
        if a.only and path.stem not in a.only:continue
        if not a.only and not a.all and path.stem not in pilot_ids:continue
        registry.append(generate(path))
    tdir=FORMAL/'PackingCertificates/Algebraic/Generated'
    templates=[dict(module=x.relative_to(FORMAL).as_posix(),sha256=filehash(x))for x in sorted(tdir.glob('*.lean'))]
    registryfile=HERE/('generated3d-all-registry.json'if a.all else 'generated3d-registry.json')
    registryfile.write_bytes((json.dumps(dict(schema='algebraic-packing-registry-v1',
        status='GENERATION_NOT_FORMAL_VERIFICATION',canonical_data_modules=templates,records=registry),indent=2)+'\n').replace('\n','\r\n').encode('utf8'))
    print(json.dumps(dict(generated_records=len(registry),status='NOT_LEAN_VERIFIED')))

if __name__=='__main__':main()
