"""Regenerate lean-optimality/PackingOptimality/LemmaF5Sphere.lean from certificates.json.

The certificates (interval partitions and line bounds, exact rationals) were found by optsphere2.py; the band
interpolation and the one-variable segments (seg.py) are in band_final.lean. Lean checks everything.
Usage: python3 scripts/optimality/lemma_f5/build.py
"""
import json, os, sys
from fractions import Fraction as Fr
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from genlean2 import emit
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
C = json.load(open(os.path.join(HERE, 'certificates.json')))


def line(d):
    L = {k: Fr(v) for k, v in d.items() if k != 'kind'}; L['kind'] = d['kind']; return L


DOC = {'sphA': 'λ = 33/50: `Σ (sᵢ³ + λ sᵢ) ≤ 1.87333` (the maximum is ≈ 1.86930).',
       'sphB': 'λ = 147/200: `Σ (sᵢ³ + λ sᵢ) ≤ 1.99925` (the maximum is ≈ 1.99487).',
       'sphC': 'λ = 161/200: `Σ (sᵢ³ + λ sᵢ) ≤ 2.12352` (the maximum is ≈ 2.11782).',
       'cs5': 'Five coordinates with `sᵢ² ≤ 9/20`, λ = 29/70: `Σ (sᵢ³ + λ sᵢ) ≤ 99/70` (the maximum is ≈ 1.40607).'}
HDR = '''import Mathlib

/-!
# Sphere bounds for Lemma F in dimension 5 (generated)

Each `sph*` lemma bounds `Σᵢ (sᵢ³ + λ sᵢ)` on the nonnegative part of the unit sphere: four coordinates for the
band, and five with the cap `sᵢ² ≤ 9/20` for the far region (`cs5`).

* A tournament reduces the general case to `s₀` being the largest coordinate (`*_core`).
* The range of `s₀` and of the other coordinates is cut into intervals. On each interval `s³ + λ s ≤ α + β s²`
  holds by an exact factorization: a tangent `(s - t)² (u - s)` or a chord `(s - a) (b - s) (s - u)`.
* For every choice of intervals, the resulting linear bound in the `sᵢ²` (with `Σ sᵢ² = 1` and `sᵢ² ≤ s₀²`) is
  closed by `linarith`.

`band_final` interpolates the three band bounds in `λ` and closes the one-variable inequality in `c`.

Generated by `scripts/optimality/lemma_f5/build.py` from `certificates.json`. The certificates were found by a
small search over interval partitions (`optsphere2.py`, exact linear programs per case); Lean checks every case.
-/

set_option linter.unusedVariables false

namespace PackingOptimality.LemmaF5Sphere
'''


def main():
    parts = [HDR]
    for name in ('sphA', 'sphB', 'sphC', 'cs5'):
        c = C[name]
        big = [(Fr(a), Fr(b), line(L)) for a, b, L in c['big']]
        small = [(Fr(a), Fr(b), line(L)) for a, b, L in c['small']]
        assert c['lp_bound'] <= float(Fr(c['U'])) - 1e-7
        parts.append(f'/-! ## {name} -/\n')
        parts.append(emit(name, Fr(c['lam']), c['n'], big, small, Fr(c['U']), Fr(c['cap']) if c['cap'] else None, DOC[name]))
    parts.append(open(os.path.join(HERE, 'band_final.lean')).read())
    parts.append('end PackingOptimality.LemmaF5Sphere\n')
    out = os.path.join(ROOT, 'lean-optimality', 'PackingOptimality', 'LemmaF5Sphere.lean')
    open(out, 'w').write('\n'.join(parts))
    print('wrote', out)


if __name__ == '__main__':
    main()
