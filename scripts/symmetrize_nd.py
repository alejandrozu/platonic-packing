"""Symmetrize a 4D-6D record at fixed container size: scripts/symmetrize.py for the regular polytopes (14 Nov 2026).

As in 3D: the container stays at the record's s_full (centred at the origin), and pieces are moved one at a time,
outermost first, onto the fixed set of a subgroup K of the container's symmetry group, oriented so that K maps the
piece onto itself (group average c* = mean h c, R* = polar(mean h R phi(h)^T)). A move is kept only if the piece
keeps a wall gap >= 1e-7 and a separating hyperplane with gap >= 1e-7 (piece edges) to every neighbour
(ndsim.planes_lp). The symmetry groups are generated by the reflections that map the vertex set to itself (all
regular polytopes have Coxeter groups). Candidate subgroups: the stabilizers of the container's vertices, edge
midpoints, facet centres and the centres of facet intersections, their rotation parts, and single mirrors.

The record is rewritten with exactly orthogonal rational rotations for the moved pieces (claim_nd.rational_rotation),
fresh rational separating hyperplanes for every near pair, and the same s_full; certify_nd.py checks it.

Usage: python3 scripts/symmetrize_nd.py RECORD.json [OUT.json]
       python3 scripts/symmetrize_nd.py --all OUTDIR [problem ...]
"""
import json, os, sys, math, itertools, time, glob
import numpy as np
from scipy.spatial import cKDTree
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'src')); sys.path.insert(0, os.path.join(ROOT, 'scripts'))
import ndsim
from claim_nd import rational_rotation, DEN

GAP = WALL = 1e-7                 # piece edges, as in the records
MOVE = 0.35                       # largest centre move (piece edges)
ANGLE = math.radians(25)
TOL = 1e-6
_GROUPS = {}
_SUB = {}


def key(M, k=5): return tuple(np.round(np.asarray(M), k).ravel())


def polar(M):
    U, _, Vt = np.linalg.svd(M); R = U @ Vt
    if np.linalg.det(R) < 0: U[:, -1] *= -1; R = U @ Vt
    return R


def group(pid):
    """all orthogonal matrices mapping the vertex set of the polytope to itself, as an array |G| x d x d"""
    if pid in _GROUPS: return _GROUPS[pid]
    V = np.array(ndsim.data()[pid]['Vf'], float); V = V / np.linalg.norm(V, axis=1).max()
    t = cKDTree(V); nr = np.linalg.norm(V, axis=1); d = V.shape[1]
    refl = {}
    for i in range(len(V)):
        for j in range(i + 1, len(V)):
            if abs(nr[i] - nr[j]) > 1e-9: continue
            u = V[i] - V[j]; u /= np.linalg.norm(u)
            s = u[np.flatnonzero(np.abs(u) > 1e-9)[0]]
            k = key(u if s > 0 else -u, 6)
            if k in refl: continue
            M = np.eye(d) - 2 * np.outer(u, u)
            if t.query(V @ M.T)[0].max() < 1e-7: refl[k] = M
    gens = list(refl.values())
    S = {key(np.eye(d)): np.eye(d)}; fr = [np.eye(d)]
    while fr:
        new = []
        for a in fr:
            for g in gens:
                m = g @ a; k = key(m)
                if k not in S: S[k] = m; new.append(m)
        fr = new
    G = np.array(list(S.values())); _GROUPS[pid] = (G, np.array(gens))
    return _GROUPS[pid]


class GeoND:
    def __init__(self, rec):
        self.rec = rec
        D = ndsim.data(); P, Q = D[rec['piece']], D[rec['container']]
        self.pb = ndsim.Problem(rec['piece'], rec['container'])
        self.d = P['dim']; self.eP = P['edge']
        self.V = np.array(P['Vf'], float)                       # exact frame
        self.Vt = cKDTree(self.V)
        self.N = np.array(Q['N'], float); self.beta = np.array(Q['beta'], float)
        from multiquad import parse
        self.mu = float(parse(rec['mu'])) if isinstance(rec['mu'], str) else float(rec['mu'])
        self.s = float(rec['s_full'])
        self.circ = float(np.linalg.norm(self.V, axis=1).max())
        self.G, self.refl = group(rec['container'])
        self.CV = np.array(Q['Vf'], float)
        if rec['container'] not in _SUB: _SUB[rec['container']] = self._subgroups(Q)      # per container, once
        self.subgroups = _SUB[rec['container']]

    # -- geometry (exact frame; gaps in piece edges)
    def wall(self, c, R):
        X = c + self.V @ R.T
        return float((self.s * self.mu * self.beta - (X @ self.N.T).max(0)).min()) / self.eP

    def gaps(self, C, Rs, pairs):
        if not len(pairs): return np.zeros(0), np.zeros((0, self.d))
        sc = self.pb.scale
        g, U, _ = ndsim.planes_lp(self.pb, np.asarray(C) * sc, np.asarray(Rs), np.asarray(pairs, np.int64), need=GAP * self.pb.edge * 1.5)
        return g / self.pb.edge, U

    def legal_piece(self, i, c, R, C, Rs):
        if self.wall(c, R) < WALL * 1.01: return False
        C2 = C.copy(); C2[i] = c; R2 = list(Rs); R2[i] = R
        nb = [j for j in range(len(C)) if j != i and np.linalg.norm(C2[j] - c) < 2 * self.circ * 1.001]
        if not nb: return True
        pairs = np.array([(min(i, j), max(i, j)) for j in nb], np.int64)
        g, _ = self.gaps(C2, R2, pairs)
        return bool(g.min() >= GAP * 1.01)

    # -- symmetry
    def is_sym(self, M):
        """the permutation-based symmetry p of the piece nearest to M (orthogonal, maps V to V), or None"""
        dd, idx = self.Vt.query(self.V @ M.T)
        if dd.max() > 0.25 * self.eP: return None
        p = np.linalg.lstsq(self.V, self.V[idx], rcond=None)[0].T
        if np.abs(p @ p.T - np.eye(self.d)).max() > 1e-9: return None
        if self.Vt.query(self.V @ p.T)[0].max() > 1e-9: return None
        return p

    def stabilizer(self, c, R):
        Gc = np.einsum('gab,b->ga', self.G, c)
        m = np.flatnonzero(np.linalg.norm(Gc - c, axis=1) < TOL)
        n = 0
        for k in m:
            M = R.T @ self.G[k] @ R
            if self.Vt.query(self.V @ M.T)[0].max() < TOL: n += 1
        return n

    def packing_group(self, C, Rs):
        t = cKDTree(C); n = 0
        GC = np.einsum('gab,nb->gna', self.G, C)
        for k in range(len(self.G)):
            dd, idx = t.query(GC[k])
            if dd.max() > TOL: continue
            ok = True
            for i in range(len(C)):
                M = Rs[idx[i]].T @ self.G[k] @ Rs[i]
                if self.Vt.query(self.V @ M.T)[0].max() > TOL: ok = False; break
            n += ok
        return n

    def _subgroups(self, Q):
        CV = self.CV; F = [set(f) for f in Q['facets']]
        pts = [v for v in CV]
        e2 = np.min([np.sum((CV[a] - CV[b]) ** 2) for a, b in Q['edges'][:1]])
        pts += [(CV[a] + CV[b]) / 2 for a, b in Q['edges']]
        pts += [CV[sorted(f)].mean(0) for f in F]
        seen = set()
        for a, b in itertools.combinations(range(len(F)), 2):
            x = F[a] & F[b]
            if len(x) >= 3:
                k = frozenset(x)
                if k not in seen: seen.add(k); pts.append(CV[sorted(x)].mean(0))
        groups = {}

        def add(idx):
            if len(idx) < 2: return
            k = frozenset(int(i) for i in idx)
            if k not in groups: groups[k] = np.array(sorted(idx))
        for x in pts:
            st = np.flatnonzero(np.linalg.norm(np.einsum('gab,b->ga', self.G, x) - x, axis=1) < 1e-9)
            add(st)
            add([i for i in st if np.linalg.det(self.G[i]) > 0])
        Gk = {key(g): i for i, g in enumerate(self.G)}
        for r in self.refl:
            add([Gk[key(np.eye(self.d))], Gk[key(r)]])
        out = []
        for idx in groups.values():
            H = self.G[idx]; Pi = H.mean(0)
            w, v = np.linalg.eigh((Pi + Pi.T) / 2)
            out.append((H, Pi, v[:, w > 0.5]))
        out.sort(key=lambda t: -len(t[0]))
        return out

    def target(self, c, R, H, Pi):
        phi = []
        for h in H:
            p = self.is_sym(R.T @ h @ R)
            if p is None: return None
            if np.linalg.norm(R.T @ h @ R - p) > 2 * math.sqrt(2) * math.sin(ANGLE / 2): return None
            phi.append(p)
        Rs = polar(sum(h @ R @ p.T for h, p in zip(H, phi)) / len(H))
        if any(np.linalg.norm(h @ Rs - Rs @ p) > 1e-9 for h, p in zip(H, phi)): return None
        c_ = max(-1.0, min(1.0, 1 - np.linalg.norm(Rs - R) ** 2 / 4))
        if math.acos(c_) > ANGLE * 1.5: return None
        return Pi @ c, Rs

    def positions(self, cs, Rt, B, c0):
        hf = (self.V @ Rt.T @ self.N.T).max(0)
        rhs = self.s * self.mu * self.beta - WALL * 1.02 * self.eP - hf
        k = B.shape[1]
        if k == 0: yield np.zeros(self.d); return
        if k == 1:
            u = B[:, 0]; t0 = float(cs @ u); a = self.N @ u
            hi = min([r / x for r, x in zip(rhs, a) if x > 1e-12] or [math.inf])
            lo = max([r / x for r, x in zip(rhs, a) if x < -1e-12] or [-math.inf])
            cand = [t for t in (hi, lo) if math.isfinite(t) and abs(t - t0) <= MOVE * self.eP]
            cand += [t for t in sorted(np.linspace(t0 - MOVE * self.eP, t0 + MOVE * self.eP, 41), key=lambda t: abs(t - t0)) if lo <= t <= hi]
            for t in cand: yield t * u
            return
        yield cs
        rng = np.random.default_rng(0)
        for r in (0.002, 0.005, 0.01, 0.02, 0.05, 0.1):
            for _ in range(6):
                w = B @ rng.normal(size=k); w /= np.linalg.norm(w)
                yield cs + r * self.eP * w

    def symmetrize_piece(self, i, C, Rs):
        c0, R0 = C[i], Rs[i]
        cur = self.stabilizer(c0, R0)
        for H, Pi, B in self.subgroups:
            if len(H) <= cur: break
            if np.linalg.norm(c0 - Pi @ c0) > MOVE * self.eP: continue
            t = self.target(c0, R0, H, Pi)
            if t is None: continue
            cs, Rt = t
            for c in self.positions(cs, Rt, B, c0):
                if self.legal_piece(i, c, Rt, C, Rs): return c, Rt, len(H)
        return None


def rot_of(piece_row, d):
    S = np.zeros((d, d)); k = d
    for a in range(d):
        for b in range(a + 1, d): S[a, b] = piece_row[k]; S[b, a] = -piece_row[k]; k += 1
    D = np.diag(piece_row[k:k + d])
    return D @ np.linalg.solve(np.eye(d) - S, np.eye(d) + S)


def load(fn):
    r = json.load(open(fn)); d = r['dim']
    P = np.array(r['pieces'], float)
    C = P[:, :d].copy(); Rs = [rot_of(row, d) for row in P]
    return r, C, Rs


def measure(geo, C, Rs):
    st = [geo.stabilizer(C[i], Rs[i]) for i in range(len(C))]
    return {'packing_group': geo.packing_group(C, Rs), 'symmetric_pieces': sum(x > 1 for x in st),
            'stabilizer_sum': int(sum(st) - len(st)), 'stabilizers': sorted(st, reverse=True)}


def run(fn, passes=3):
    r, C, Rs = load(fn)
    geo = GeoND(r)
    before = measure(geo, C, Rs)
    outer = np.argsort(-((C @ geo.N.T) / geo.beta).max(1))
    moved = {}
    for _ in range(passes):
        changed = False
        for i in outer:
            res = geo.symmetrize_piece(int(i), C, Rs)
            if res: C[i], Rs[i] = res[0], res[1]; moved[int(i)] = res[2]; changed = True
        if not changed: break
    after = measure(geo, C, Rs)
    return r, geo, C, Rs, before, after, moved


def write(r, geo, C, Rs, before, after, moved, out, src_file):
    d = geo.d; rec = dict(r); pieces = [list(x) for x in r['pieces']]
    Rx = [rot_of(row, d) for row in np.array(pieces, float)]
    for i in moved:
        S, sg, R_ex = rational_rotation(Rs[i])
        pieces[i] = [*map(float, C[i]), *[float(x) for x in S], *sg]
        Rx[i] = R_ex
    Cx = np.array([row[:d] for row in pieces], float)
    pairs = ndsim.near_pairs(Cx * geo.pb.scale, (2 * geo.pb.circ) ** 2 * 1.01 ** 2)
    g, U, _ = ndsim.planes_lp(geo.pb, Cx * geo.pb.scale, np.array(Rx), pairs)
    planes = []
    for (i, j), u in zip(pairs.tolist(), U):
        uq = np.round(u * DEN) / DEN
        xa = ((Cx[i] + geo.V @ Rx[i].T) @ uq).max(); xb = ((Cx[j] + geo.V @ Rx[j].T) @ uq).min()
        planes.append([i, j, *uq.tolist(), (xa + xb) / 2])
    rec['pieces'] = pieces; rec['planes'] = planes
    rec['clearance'] = dict(r['clearance'], min_pair_gap=float(g.min() / geo.pb.edge) if len(g) else None,
                            min_wall_gap=float(min(geo.wall(Cx[i], Rx[i]) for i in range(len(Cx)))))
    rec['symmetrized'] = {'from': src_file, 'from_source_hash': (r.get('source') or {}).get('hash'), 'container': 'unchanged (same s_full)',
                          'before': before, 'after': after, 'moved_pieces': sorted(moved),
                          'method': 'scripts/symmetrize_nd.py: pieces moved one at a time onto symmetric placements of the container, '
                                    'each move kept only if the packing stays legal with the same clearances'}
    for k in ('certificate', 'closed_form_source', 'closed_form_confirmation'): rec.pop(k, None)
    json.dump(rec, open(out, 'w'), indent=1)


