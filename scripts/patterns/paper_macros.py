# ---- per-family-group classification table (docs/patterns-paper/table_families.tex)
import glob, collections
R = {}
for f in glob.glob(os.path.join(ROOT, 'records', '*', '*_n*.json')):
    try: d = json.load(open(f))
    except Exception: continue
    if isinstance(d, dict) and 'pieces' in d and 's_full' in d: R[d.get('record_id') or os.path.basename(f)[:-5]] = d
F = {x['record_id']: x for x in json.load(open(os.path.join(ROOT, 'docs', 'patterns', 'features3d.json')))}
I = json.load(open(os.path.join(ROOT, 'docs', 'patterns', 'inherit3d.json')))
plat_ids = set()
by = collections.defaultdict(dict)
for rid, d in R.items(): by[rid.rsplit('_n', 1)[0]][d['n']] = d
for fam_, dd in by.items():
    ns = sorted(dd)
    for a, b in zip(ns, ns[1:]):
        if b == a + 1 and abs(dd[a]['s_full'] - dd[b]['s_full']) < 1e-9 * dd[a]['s_full']:
            plat_ids.add(f'{fam_}_n{a:02d}'); plat_ids.add(f'{fam_}_n{b:02d}')
def grp(d):
    g = (d.get('family') or '').lower()
    dim = d.get('dim', 3)
    if dim != 3: return f'{dim}D regular polytopes'
    if g in ('platonic', ''): return 'Platonic pairs'
    if g.startswith('arch'): return 'Archimedean'
    if g.startswith('cat'): return 'Catalan'
    if g.startswith('pris'): return 'Prisms and antiprisms'
    return g.capitalize()
rows = collections.OrderedDict()
for rid, d in R.items():
    g = grp(d); r = rows.setdefault(g, collections.Counter()); r['fams_set'] = 0
    r['records'] += 1
    r['plateau'] += rid in plat_ids
    r['closed'] += bool(d.get('closed_form_conjecture'))
    x = F.get(rid)
    if x:
        r['feat'] += 1
        r['sym'] += x['sym']['order'] > 1
        r['lat'] += bool(x['lattice'] and all((l or {}).get('lattice') for l in x['lattice']) and len(x['orient']) <= 4 and x['n'] >= 4)
        r['one'] += len(x['orient']) == 1
fams_by_group = collections.defaultdict(set)
for rid, d in R.items(): fams_by_group[grp(d)].add(rid.rsplit('_n', 1)[0])
frozen_by_group = collections.Counter()
for fam_, res in I.items():
    gname = grp(next(iter(by[fam_].values())))
    frozen_by_group[gname] += sum(1 for k, v in res.items() if v >= 1.0)
order = ['Platonic pairs', 'Archimedean', 'Catalan', 'Prisms and antiprisms', '4D regular polytopes',
         '5D regular polytopes', '6D regular polytopes']
T = ['\\begin{tabular}{lrrrrrrrr}', '\\toprule',
     'Group & families & records & on a plateau & closed form & symmetric & lattice window & one orientation & frozen subsets \\\\',
     '\\midrule']
for g in order + [g for g in rows if g not in order]:
    if g not in rows: continue
    r = rows[g]; nf = len(fams_by_group[g])
    feat = r['feat'] > 0
    T.append(f"{g} & {nf} & {r['records']:,} & {r['plateau']:,} & {r['closed']:,} & "
             + (f"{r['sym']:,} & {r['lat']:,} & {r['one']:,} & {frozen_by_group[g]:,}" if feat else '-- & -- & -- & --') + ' \\\\')
T += ['\\bottomrule', '\\end{tabular}']
open(os.path.join(ROOT, 'docs', 'patterns-paper', 'table_families.tex'), 'w').write('\n'.join(T) + '\n')
print('\n'.join(T))
